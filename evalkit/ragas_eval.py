"""
Thin wrapper around RAGAS generation-quality metrics. These are naturally
chunking-agnostic: they judge the FINAL retrieved context text + generated
answer against the reference answer/question, by content -- not by matching
against a pre-labeled chunk_id. So no span-overlap plumbing is needed here,
unlike the retrieval metrics in metrics.py / span_matching.py.

Requires: pip install ragas datasets langchain-huggingface
"""

from __future__ import annotations

from typing import Any

from datasets import Dataset
from langchain_huggingface import HuggingFaceEmbeddings
from langchain_openai import ChatOpenAI
from pydantic import SecretStr
from ragas import RunConfig, evaluate
from ragas.embeddings import LangchainEmbeddingsWrapper
from ragas.llms import LangchainLLMWrapper
from ragas.metrics import (
    AnswerSimilarity,
    answer_correctness,
    answer_relevancy,
    context_precision,
    context_recall,
    faithfulness,
)

from config import LLM_MODEL, RAGAS_EMBED_MODEL


METRIC_MAP = {
    "answer_correctness": answer_correctness,
    "answer_relevancy": answer_relevancy,
    "context_precision": context_precision,
    "context_recall": context_recall,
    "faithfulness": faithfulness,
}


def build_ragas_dataset(rows: list[dict]):
    """
    rows: [{
        "question": str,
        "answer": str,                 # generated by your system
        "contexts": List[str],         # retrieved chunk texts actually sent to the LLM
        "ground_truth": str,           # reference_answer from synthetic dataset
    }, ...]
    """
    return Dataset.from_list(rows)


def run_ragas_eval(
    rows: list[dict],
    metrics: list[str] | None = None,
    embed_model: str | None = RAGAS_EMBED_MODEL,
    num_workers: int = 1,
    timeout: int = 1000,
    llm: Any | None = None,
    llm_model: str = LLM_MODEL,
    llm_base_url: str | None = None,
    llm_api_key: str | None = None,
) -> Any:
    """
    Run RAGAS evaluation on the given rows.

    Args:
        rows: List of dicts with question, answer, contexts, ground_truth
        metrics: List of metric names to compute. Defaults to all 6 metrics.
        embed_model: Embedding model name for answer_similarity (e.g. "intfloat/multilingual-e5-base")
        num_workers: Number of parallel workers for RAGAS evaluation
        timeout: Timeout in seconds for RAGAS evaluation (default 1000)
        llm: Pre-configured LLM wrapper (LangchainLLMWrapper). If None, creates one from llm_* params.
        llm_model: Model name to use (default "gpt-4o-mini")
        llm_base_url: OpenAI-compatible API base URL
        llm_api_key: API key for the LLM

    Returns:
        ragas EvaluationResult object (call .to_pandas() for DataFrame)
    """
    if metrics is None:
        metrics = list(METRIC_MAP.keys()) + ["answer_similarity"]

    # Build embeddings instance for both AnswerSimilarity and evaluate()
    ragas_embeddings = None
    if embed_model:
        ragas_embeddings = LangchainEmbeddingsWrapper(
            HuggingFaceEmbeddings(
                model_name=embed_model,
                model_kwargs={"trust_remote_code": True},
            )
        )

    selected_metrics = []
    for m in metrics:
        if m in METRIC_MAP:
            selected_metrics.append(METRIC_MAP[m])
        elif m == "answer_similarity":
            if not ragas_embeddings:
                raise ValueError("answer_similarity requires embed_model")
            selected_metrics.append(AnswerSimilarity(embeddings=ragas_embeddings))
        else:
            raise ValueError(
                f"Unknown metric: {m}. Available: {list(METRIC_MAP.keys()) + ['answer_similarity']}"
            )

    ds = build_ragas_dataset(rows)

    # Create LLM wrapper if not provided
    if llm is None:
        if llm_base_url and llm_api_key:
            from config import LLM_BASE_URL, LLM_MAX_RETRIES
            from evalkit.llm_http import http_clients

            clients = (
                http_clients(timeout)
                if llm_base_url.rstrip("/") == LLM_BASE_URL.rstrip("/")
                else {}
            )
            if "async_http_client" in clients:
                clients["http_async_client"] = clients.pop("async_http_client")
            chat_llm = ChatOpenAI(
                model=llm_model,
                base_url=llm_base_url,
                api_key=SecretStr(llm_api_key),
                timeout=timeout,
                max_retries=LLM_MAX_RETRIES,
                **clients,
            )
            llm = LangchainLLMWrapper(chat_llm)
        else:
            raise ValueError(
                "llm parameter required. Either pass a LangchainLLMWrapper, "
                "or provide llm_base_url and llm_api_key"
            )

    # RunConfig with timeout and workers
    run_config = RunConfig(timeout=timeout, max_workers=num_workers)

    eval_kwargs = {
        "metrics": selected_metrics,
        "run_config": run_config,
    }

    # Pass embeddings to evaluate() for context-related metrics
    if ragas_embeddings:
        eval_kwargs["embeddings"] = ragas_embeddings

    # Pass LLM if provided
    if llm is not None:
        eval_kwargs["llm"] = llm

    result = evaluate(ds, **eval_kwargs)
    return result
